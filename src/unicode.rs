pub fn casefold(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    for c in text.chars() {
        match CASEFOLD.binary_search_by_key(&(c as u32), |row| row.0) {
            Ok(index) => result.push_str(CASEFOLD[index].1),
            Err(_) => result.push(c),
        }
    }
    result
}
