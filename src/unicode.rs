/// CPython html.unescape, including legacy names and invalid numeric references.
pub fn html_unescape(text: &str) -> String {
    let mut output = String::with_capacity(text.len());
    let mut position = 0;
    while let Some(relative) = text[position..].find('&') {
        let start = position + relative;
        output.push_str(&text[position..start]);
        let rest = &text[start + 1..];
        if let Some(number) = rest.strip_prefix('#') {
            let hexadecimal = number.starts_with(['x', 'X']);
            let digits = if hexadecimal { &number[1..] } else { number };
            let count = digits
                .bytes()
                .take_while(|c| {
                    if hexadecimal {
                        c.is_ascii_hexdigit()
                    } else {
                        c.is_ascii_digit()
                    }
                })
                .count();
            if count != 0 {
                let mut value = 0u32;
                for byte in digits[..count].bytes() {
                    value = value
                        .saturating_mul(if hexadecimal { 16 } else { 10 })
                        .saturating_add(
                            (byte as char)
                                .to_digit(if hexadecimal { 16 } else { 10 })
                                .unwrap(),
                        );
                }
                let end = start + 2 + usize::from(hexadecimal) + count;
                position = end + usize::from(text.as_bytes().get(end) == Some(&b';'));
                if let Some((_, replacement)) = INVALID_CHARREFS.iter().find(|(cp, _)| *cp == value)
                {
                    output.push_str(replacement);
                } else if (0xd800..=0xdfff).contains(&value) || value > 0x10ffff {
                    output.push('\u{fffd}');
                } else if !INVALID_CODEPOINTS.contains(&value) {
                    output.push(char::from_u32(value).expect("validated scalar"));
                }
                continue;
            }
        }
        let mut length = 0;
        for (count, (offset, c)) in rest.char_indices().enumerate() {
            if count == 32 || matches!(c, '\t' | '\n' | '\u{c}' | ' ' | '<' | '&' | '#' | ';') {
                break;
            }
            length = offset + c.len_utf8();
        }
        if length != 0 {
            if rest.as_bytes().get(length) == Some(&b';') {
                length += 1;
            }
            let token = &rest[..length];
            let mut found = None;
            for end in token
                .char_indices()
                .map(|(i, _)| i)
                .chain(std::iter::once(token.len()))
                .rev()
            {
                if end == 0 {
                    continue;
                }
                if let Ok(index) = HTML5.binary_search_by(|row| row.0.cmp(&token[..end])) {
                    found = Some((end, HTML5[index].1));
                    break;
                }
            }
            if let Some((end, replacement)) = found {
                output.push_str(replacement);
                output.push_str(&token[end..]);
                position = start + 1 + length;
                continue;
            }
        }
        output.push('&');
        position = start + 1;
    }
    output.push_str(&text[position..]);
    output
}
